"""Golden replay of the baseline wargame core (tag wargame-baseline-6982407).

The fixture is produced by::

    python3 scripts/run_wargame_core_demo.py \
        --scenario <sdk>/Data/Data/scenarios/1231.json \
        --map <sdk>/Data/Data/maps/map_123/basic.json \
        --ticks 300 --seed 20261021 \
        --out tests/fixtures/golden_core_1231_seed20261021.json

Set ``GEORULES_GOLDEN=1`` to run it (about 13 s); the default test suite only
checks that the fixture is well formed.

The Taiwan campaign's own map (map_9001) is generated by
``scripts/build_campaign_map.py`` and is not committed, so its golden replay
must be recorded wherever that map exists (see docs/geo_engine/P0_status.md).
"""

from __future__ import annotations

import json
import os
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SITUATION3D = os.path.dirname(HERE)
if SITUATION3D not in sys.path:
    sys.path.insert(0, SITUATION3D)

FIXTURE = os.path.join(HERE, "fixtures", "golden_core_1231_seed20261021.json")
SDK = "/remote-home/lizilong/shenji_agent/land_wargame_sdk/Data/Data"
SCENARIO = os.path.join(SDK, "scenarios", "1231.json")
MAP = os.path.join(SDK, "maps", "map_123", "basic.json")


class TestGoldenReplay(unittest.TestCase):
    def test_fixture_is_well_formed(self):
        with open(FIXTURE, encoding="utf-8") as fh:
            payload = json.load(fh)
        data = payload["result"]
        self.assertEqual(payload["seed"], 20261021)
        self.assertEqual(data["scenario_id"], 1231)
        self.assertEqual(data["tick"], 300)
        self.assertEqual(len(data["units"]), 12)
        self.assertEqual(len(data["events"]), 85)
        self.assertEqual(data["score"], {"red": 24, "blue": 154})

    @unittest.skipUnless(os.environ.get("GEORULES_GOLDEN") == "1",
                         "set GEORULES_GOLDEN=1 to run the 300-tick replay")
    def test_replay_is_bit_identical(self):
        from wargame_core import engine, scenario
        state = scenario.load_scenario(SCENARIO, MAP, seed=20261021,
                                       tick_seconds=30.0)
        result = engine.run_demo(state, max_ticks=300)
        with open(FIXTURE, encoding="utf-8") as fh:
            expected = json.load(fh)["result"]
        self.assertEqual(result, expected)


if __name__ == "__main__":
    unittest.main()
