"""Golden replay manifest for the Taiwan landing campaign.

The campaign map ``map_9001`` is generated by ``scripts/build_campaign_map.py``
and is gitignored, so the 20 MB replay output cannot be committed.  Instead
``tests/fixtures/golden_taiwan_campaign_manifest.json`` pins:

* the map file hashes the replay was recorded against;
* seed/tick parameters and event/stage counts;
* the sha256 of the replay output.

Set ``GEORULES_TW=1`` (about 20 s) to re-run the campaign and verify the hash.
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SITUATION3D = os.path.dirname(HERE)
if SITUATION3D not in sys.path:
    sys.path.insert(0, SITUATION3D)

MANIFEST = os.path.join(HERE, "fixtures", "golden_taiwan_campaign_manifest.json")
MAP = os.path.join(SITUATION3D, "web", "data", "campaign_maps", "map_9001")


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


class TestTaiwanGolden(unittest.TestCase):
    def test_manifest_is_well_formed(self):
        with open(MANIFEST, encoding="utf-8") as fh:
            man = json.load(fh)
        self.assertEqual(man["case"], "taiwan_landing")
        self.assertEqual(man["seed"], 20261021)
        self.assertEqual(man["tick_count"], 1440)
        self.assertEqual(man["events"], 934)
        self.assertEqual(man["stages"], 7)
        self.assertEqual(man["outcome"]["engine"]["score"], {"red": 78, "blue": 221})
        self.assertEqual(len(man["output"]["sha256"]), 64)

    def test_map_hashes_match_manifest(self):
        with open(MANIFEST, encoding="utf-8") as fh:
            man = json.load(fh)
        basic = os.path.join(MAP, "basic.json")
        if not os.path.isfile(basic):
            self.skipTest("map_9001 not generated in this checkout")
        self.assertEqual(_sha256(basic), man["map"]["basic_sha256"])
        self.assertEqual(_sha256(os.path.join(MAP, "cost.pickle")),
                         man["map"]["cost_sha256"])

    @unittest.skipUnless(os.environ.get("GEORULES_TW") == "1",
                         "set GEORULES_TW=1 to re-run the 1440-tick campaign")
    def test_campaign_output_is_bit_identical(self):
        with open(MANIFEST, encoding="utf-8") as fh:
            man = json.load(fh)
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.check_call(
                [sys.executable, "scripts/run_campaign.py",
                 "--case", "taiwan_landing", "--out", tmp,
                 "--seed", str(man["seed"])],
                cwd=SITUATION3D)
            out = os.path.join(tmp, "taiwan_campaign.json")
            self.assertEqual(_sha256(out), man["output"]["sha256"])


if __name__ == "__main__":
    unittest.main()
